#!/usr/bin/env node
/** Appends the conversion results (cars + map) to ASSET_REPORT.md. Run after the other steps. */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const out = path.join(here, 'out');
const pub = path.join(root, 'apps/client/public/assets');
const reportPath = path.join(root, 'ASSET_REPORT.md');
const MARK = '\n## Conversion results\n';

let md = existsSync(reportPath) ? readFileSync(reportPath, 'utf8') : '# Asset Report\n';
if (md.includes(MARK)) md = md.slice(0, md.indexOf(MARK));

const cars = JSON.parse(readFileSync(path.join(pub, 'cars.json'), 'utf8')).cars;
const rep = existsSync(path.join(out, 'cars_report.json')) ? JSON.parse(readFileSync(path.join(out, 'cars_report.json'), 'utf8')) : { excluded: [] };
const mb = (f) => (existsSync(f) ? (statSync(f).size / 1e6).toFixed(2) : '–');

const lines = [
  MARK,
  "Generated by `tools/asset-pipeline/report.mjs` from the pipeline outputs. Game space: metres, +Y up, +Z forward, +X = driver's left; car origin at mid-wheelbase on the ground.",
  '',
  '### Cars',
  '',
  '| Car | Length × width × height (m) | Wheelbase | Wheels found by | Generic wheel fallback | Steering wheel | Cockpit anchor | Interior | LOD0 / LOD1 / LOD2 (MB) |',
  '|---|---|---|---|---|---|---|---|---|',
];
for (const c of cars) {
  const meta = JSON.parse(readFileSync(path.join(out, 'cars', `${c.id}.json`), 'utf8'));
  const srcs = [...new Set(Object.values(meta.wheels).map((w) => w.source))].join(', ');
  const anchor = meta.steering ? 'steering wheel' : meta.log.some((l) => l.startsWith('eye from seat')) ? 'seat' : 'roof heuristic';
  lines.push(
    `| ${c.name} (\`${c.id}\`) | ${c.dims.length.toFixed(2)} × ${c.dims.width.toFixed(2)} × ${c.dims.height.toFixed(2)} | ${c.wheelbase.toFixed(2)} | ${srcs} | ${c.genericWheels.length ? c.genericWheels.join(', ') : 'no'} | ${c.steering ? 'separate, rotates' : 'generic overlay / static'} | ${anchor} | ${c.hasInterior ? 'yes' : 'no (generated dash)'} | ${c.lods.map((l) => mb(path.join(root, 'apps/client/public', l.split('?')[0]))).join(' / ')} |`,
  );
}
lines.push(
  '',
  'Wheel sources: `name` = tyre meshes found by name and clustered per corner; `geometry` = ring-shaped parts found low in each corner; `mirrored` = copied from the other side of the axle; `estimated` = placed from body bounds; `+r` = radius corrected from the real car length.',
);
if (rep.excluded?.length) {
  lines.push('', '**Excluded:**');
  for (const e of rep.excluded) lines.push(`- \`${e.id}\`: ${e.reason}`);
}
lines.push('', '- `2020_McLaren_720S_GT3(1)` is byte-identical to `2020_McLaren_720S_GT3` and was skipped as a duplicate.');

const mapOut = path.join(out, 'map');
if (existsSync(path.join(mapOut, 'analysis.json'))) {
  const an = JSON.parse(readFileSync(path.join(mapOut, 'analysis.json'), 'utf8'));
  const track = JSON.parse(readFileSync(path.join(pub, 'track.json'), 'utf8'));
  lines.push('', '### Map (Nürburgring GP 2022 layout)', '');
  lines.push(`- Scale: ${an.scale.toFixed(4)} m per source unit (derived so the traced centreline equals the official 5,148 m lap).`);
  lines.push(
    `- Centreline length ${track.length.toFixed(0)} m, ${track.gates.length} checkpoint gates, sectors end at gates ${track.sectorGates.join(' and ')}, first gate from the grid: ${track.firstGate}.`,
  );
  lines.push(`- Grid: ${track.grid.length} slots taken from the painted grid boxes; start/finish = chequered line.`);
  lines.push('- Collision triangles per surface:');
  for (const [k, v] of Object.entries(an.collision)) lines.push(`  - ${k}: ${v.triangles.toLocaleString('en')} (before simplification)`);
  const files = readdirSync(path.join(pub, 'track'));
  lines.push(`- Runtime files: ${files.map((f) => `\`${f}\` ${mb(path.join(pub, 'track', f))} MB`).join(', ')}.`);
}
let total = 0;
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = path.join(d, f);
    const s = statSync(p);
    if (s.isDirectory()) walk(p);
    else total += s.size;
  }
};
walk(pub);
lines.push('', `Total runtime asset size: ${(total / 1e6).toFixed(1)} MB (Vercel Hobby static upload limit: 100 MB).`, '');
writeFileSync(reportPath, md.trimEnd() + '\n' + lines.join('\n'));
console.log('ASSET_REPORT.md updated');
